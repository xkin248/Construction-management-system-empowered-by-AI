"""Generate (never execute) the attendance/task photo-column migration.

The check-in and task-completion flow now persists only a *relative file path*
in the database (never base64). Four columns back that contract:

    attendance_logs.in_photo_path        -- selfie captured at check-in
    attendance_logs.out_photo_path       -- selfie captured at check-out
    tasks.completion_photo_path          -- proof photo taken before a worker
                                            marks a task completed
    tasks.completion_photo_at            -- when that photo was submitted;
                                            refreshed when a resubmit wins

The columns are declared in ``app/models.py``; this script writes the matching
DDL so a human can review and apply it. It is a *generator*: by default it only
writes files. It refuses to touch a database unless ``--execute`` is passed
explicitly, and it never targets the production database on its own.

Usage (from the backend directory):

    # 1) Produce the SQL file (default: no database connection at all)
    python scripts/migrate_photo_columns.py

    # 2) Write it to a custom directory
    python scripts/migrate_photo_columns.py --out-dir migrations/photo

    # 3) Apply it yourself (explicit opt-in)
    python scripts/migrate_photo_columns.py --execute

Outputs (default directory: ./migrations):
    photo_columns_migration.sql   - idempotent ALTER TABLE ... ADD COLUMN IF NOT EXISTS
    photo_columns_migration.md    - what is added, why, and how to verify/rollback
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

# (table, column, ddl type, purpose)
COLUMNS = (
    ("attendance_logs", "in_photo_path", "VARCHAR(500)",
     "worker/supervisor selfie path at check-in (relative to UPLOAD_DIR)"),
    ("attendance_logs", "out_photo_path", "VARCHAR(500)",
     "optional selfie path at check-out"),
    ("tasks", "completion_photo_path", "VARCHAR(500)",
     "worker proof photo path before marking a task completed"),
    ("tasks", "completion_photo_at", "TIMESTAMP WITH TIME ZONE",
     "when the current completion photo was submitted (refreshed on resubmit)"),
)


def build_sql() -> str:
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        "-- BuildSmart: attendance/task photo columns",
        "-- Generated: %s" % ts,
        "-- Generated by: scripts/migrate_photo_columns.py (NOT executed)",
        "--",
        "-- Stores a relative file path only; base64 image data is never persisted.",
        "-- Idempotent: safe to re-run on a database that already has the columns.",
        "",
        "BEGIN;",
        "",
    ]
    for table, column, ddl_type, purpose in COLUMNS:
        lines.append("-- %s: %s" % (column, purpose))
        lines.append(
            "ALTER TABLE %s ADD COLUMN IF NOT EXISTS %s %s;"
            % (table, column, ddl_type)
        )
    lines += [
        "",
        "COMMIT;",
        "",
        "-- Verification (expect 4 rows)",
        "SELECT table_name, column_name, data_type, character_maximum_length",
        "FROM information_schema.columns",
        "WHERE (table_name = 'attendance_logs'",
        "       AND column_name IN ('in_photo_path', 'out_photo_path'))",
        "   OR (table_name = 'tasks'",
        "       AND column_name IN ('completion_photo_path', 'completion_photo_at'))",
        "ORDER BY table_name, column_name;",
        "",
        "-- Rollback (review before running; drops captured photo paths)",
        "-- ALTER TABLE attendance_logs DROP COLUMN IF EXISTS in_photo_path;",
        "-- ALTER TABLE attendance_logs DROP COLUMN IF EXISTS out_photo_path;",
        "-- ALTER TABLE tasks DROP COLUMN IF EXISTS completion_photo_path;",
        "-- ALTER TABLE tasks DROP COLUMN IF EXISTS completion_photo_at;",
        "",
    ]
    return "\n".join(lines)


def build_md() -> str:
    rows = "\n".join(
        "| `%s` | `%s` | `%s` | %s |" % (t, c, d, p) for t, c, d, p in COLUMNS
    )
    return """# Photo column migration

Generated by `scripts/migrate_photo_columns.py`. **Not executed** - run the SQL
yourself after review.

## What is added

| Table | Column | Type | Purpose |
|---|---|---|---|
%s

## Design notes

- Only a relative path is stored (`uploads/attendance/...`, `uploads/task_completion/...`).
  Base64 image bytes are decoded on write and never persisted in the database.
- Reads are served by authenticated endpoints
  (`GET /attendance/photos/{photo_path}`, task detail `completion_photo_url`),
  not by public static hosting.
- `uploads/` must be a persistent volume in deployment, otherwise images are lost
  on container restart even though the path column survives.

## Apply

```bash
psql "$DATABASE_URL" -f migrations/photo_columns_migration.sql
```

## Verify

The generated SQL ends with an `information_schema.columns` query; it must
return exactly 4 rows.
""" % rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default="migrations",
                        help="directory for the generated files (default: ./migrations)")
    parser.add_argument("--execute", action="store_true",
                        help="actually run the DDL against DATABASE_URL (off by default)")
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    if not out_dir.is_absolute():
        out_dir = BACKEND_DIR / out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    sql_path = out_dir / "photo_columns_migration.sql"
    md_path = out_dir / "photo_columns_migration.md"
    sql_path.write_text(build_sql(), encoding="utf-8")
    md_path.write_text(build_md(), encoding="utf-8")

    print("generated: %s" % sql_path)
    print("generated: %s" % md_path)

    if not args.execute:
        print("dry run only - no database connection was opened")
        print("re-run with --execute to apply (you should review the SQL first)")
        return 0

    import os

    from sqlalchemy import create_engine, text

    url = os.getenv("DATABASE_URL")
    if not url:
        print("refusing to execute: DATABASE_URL is not set")
        return 2

    engine = create_engine(url)
    with engine.begin() as conn:
        for table, column, ddl_type, _purpose in COLUMNS:
            conn.execute(text(
                "ALTER TABLE %s ADD COLUMN IF NOT EXISTS %s %s"
                % (table, column, ddl_type)
            ))
            print("applied: %s.%s" % (table, column))
    print("done - verify with the query at the end of the SQL file")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
