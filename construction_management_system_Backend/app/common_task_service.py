"""Daily common tasks: lazy creation and read models.

The three jobs every site repeats (morning briefing, toolbox talk, housekeeping)
are *not* generated by a scheduler. A cron-style generator would need a second
process, would silently stop working when that process is not deployed, and would
create rows for projects nobody opens. Instead each read path calls
:func:`ensure_daily_instances`, which inserts whatever is missing for the day and
returns the full list. The row therefore appears the first time anyone looks, and
the unique constraint on ``(project_id, task_kind, work_date)`` means two
concurrent first-visits cannot create duplicates — the loser of the race gets an
``IntegrityError``, rolls back and simply re-reads.
"""

from datetime import date, datetime
from typing import Dict, List, Optional

from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.models import CommonTaskInstance, Worker

# Order is the order the worker sees them in during the morning.
COMMON_TASK_KINDS = ("briefing", "toolbox", "housekeeping")


def ensure_daily_instances(
    db: Session, project_id: int, work_date: Optional[date] = None
) -> List[CommonTaskInstance]:
    """Return the day's common tasks for one project, creating missing rows.

    Idempotent: calling it twice (or from two requests at the same time) leaves
    exactly one row per kind.
    """
    day = work_date or date.today()
    rows = (
        db.query(CommonTaskInstance)
        .filter(
            CommonTaskInstance.project_id == int(project_id),
            CommonTaskInstance.work_date == day,
        )
        .all()
    )
    have = {r.task_kind for r in rows}
    missing = [k for k in COMMON_TASK_KINDS if k not in have]

    if missing:
        for kind in missing:
            db.add(
                CommonTaskInstance(
                    project_id=int(project_id),
                    task_kind=kind,
                    work_date=day,
                    status="pending",
                )
            )
        try:
            db.commit()
        except IntegrityError:
            # Another request created the same day a moment earlier. Its rows are
            # the ones we want; ours are discarded.
            db.rollback()
        rows = (
            db.query(CommonTaskInstance)
            .filter(
                CommonTaskInstance.project_id == int(project_id),
                CommonTaskInstance.work_date == day,
            )
            .all()
        )

    order = {k: i for i, k in enumerate(COMMON_TASK_KINDS)}
    return sorted(rows, key=lambda r: (order.get(r.task_kind, 99), r.instance_id))


def serialize_instance(
    db: Session, inst: CommonTaskInstance, *, names: Optional[Dict[int, str]] = None
) -> Dict[str, object]:
    """One instance as a dict, including the authenticated photo URL.

    The URL is built here (not via ``response_model``) so list and detail
    responses carry identical fields — a serialisation-layer-only field used to be
    dropped by ``response_model`` on the task endpoints.
    """
    completed_name = None
    if inst.completed_by:
        if names is not None and inst.completed_by in names:
            completed_name = names[inst.completed_by]
        else:
            worker = db.query(Worker).filter(Worker.worker_id == inst.completed_by).first()
            completed_name = worker.name if worker else None

    return {
        "instance_id": inst.instance_id,
        "project_id": inst.project_id,
        "task_kind": inst.task_kind,
        "work_date": inst.work_date.isoformat() if inst.work_date else None,
        "status": inst.status or "pending",
        "photo_path": inst.photo_path,
        "photo_url": (
            f"/common-tasks/{inst.instance_id}/photo" if inst.photo_path else None
        ),
        "completed_at": (
            _iso(inst.completed_at) if inst.completed_at else None
        ),
        "completed_by": inst.completed_by,
        "completed_by_name": completed_name,
    }


def _iso(value: datetime) -> str:
    """ISO string without a trailing ``+00:00``, matching the task endpoints."""
    return value.replace(tzinfo=None).isoformat() if value.tzinfo else value.isoformat()
